/**
 * npm run seed
 * - SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY set: wipes and reloads the demo orgs' events in Supabase.
 * - otherwise: writes supabase/seed.sql (load it with psql or the SQL editor).
 * Without either, the app seeds itself in memory on start; no seeding needed for the demo.
 */
import { createClient } from "@supabase/supabase-js";
import { writeFileSync } from "node:fs";
import { DEMO_ORGS, generateEvents } from "../src/lib/seed";

const now = new Date();
const orgs = DEMO_ORGS.map((o, i) => ({ org: o, events: generateEvents(o, now, { scale: i === 0 ? 1 : 0.4, seed: 42 + i }) }));
const { SUPABASE_URL: url, SUPABASE_SERVICE_ROLE_KEY: key } = process.env;

async function main() {
  if (url && key) {
    const db = createClient(url, key, { auth: { persistSession: false } });
    for (const { org, events } of orgs) {
      const must = (r: { error: { message: string } | null }) => { if (r.error) throw new Error(r.error.message); };
      must(await db.from("orgs").upsert({ id: org.id, name: org.name, webhook_secret: org.webhookSecret }));
      must(await db.from("events").delete().eq("org_id", org.id));
      const rows = events.map((e) => ({ org_id: e.orgId, type: e.type, occurred_at: e.ts, contact_id: e.contactId, source: e.source ?? null, value: e.value ?? null, idempotency_key: e.key }));
      for (let i = 0; i < rows.length; i += 500) must(await db.from("events").insert(rows.slice(i, i + 500)));
      console.log(`${org.name}: ${rows.length} events loaded`);
    }
    return;
  }
  const q = (s?: string | number) => (s === undefined ? "null" : typeof s === "number" ? String(s) : `'${s.replace(/'/g, "''")}'`);
  let sql = "-- generated by `npm run seed`\nbegin;\n";
  for (const { org, events } of orgs) {
    sql += `insert into orgs (id, name, webhook_secret) values (${q(org.id)}, ${q(org.name)}, ${q(org.webhookSecret)}) on conflict (id) do nothing;\n`;
    sql += `delete from events where org_id = ${q(org.id)};\n`;
    for (let i = 0; i < events.length; i += 500) {
      sql += "insert into events (org_id, type, occurred_at, contact_id, source, value, idempotency_key) values\n";
      sql += events.slice(i, i + 500).map((e) => `(${q(e.orgId)}, ${q(e.type)}, ${q(e.ts)}, ${q(e.contactId)}, ${q(e.source)}, ${q(e.value)}, ${q(e.key)})`).join(",\n") + ";\n";
    }
  }
  writeFileSync("supabase/seed.sql", sql + "commit;\n");
  console.log(`wrote supabase/seed.sql (${orgs.reduce((n, o) => n + o.events.length, 0)} events)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
